// Regenerate frontend/src/data/objections.js from a fresh export of the
// static objection-handler cheatsheet (itself regenerated from Notion by
// hand — see docs/superpowers/specs/2026-08-18-objection-handler-design.md).
//
// Usage: node scripts/extract-objections.js /path/to/objection_handler_N.html
import fs from 'fs';
import path from 'path';

const srcPath = process.argv[2];
if (!srcPath) {
  console.error('Usage: node scripts/extract-objections.js /path/to/objection_handler_N.html');
  process.exit(1);
}

const html = fs.readFileSync(srcPath, 'utf8');
const match = html.match(/const OBJECTIONS = (\[.*?\]);\n/s);
if (!match) {
  console.error('Could not find "const OBJECTIONS = [...]" in the source file.');
  process.exit(1);
}

const objections = JSON.parse(match[1]);

const outPath = path.join(import.meta.dirname, '..', 'src', 'data', 'objections.js');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
const banner = `// Generated by scripts/extract-objections.js from ${path.basename(srcPath)}.
// To refresh: re-export the objection cheatsheet from Notion, then re-run
// that script against the new file.
`;
fs.writeFileSync(outPath, `${banner}export const OBJECTIONS = ${JSON.stringify(objections, null, 2)};\n`);
console.log(`Wrote ${objections.length} objections (${objections.reduce((n, o) => n + o.boxes.length, 0)} rebuttal boxes) to ${outPath}`);
